package cli

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/alexandrmotologa/n8nflow-guard/internal/fixer"
	"github.com/spf13/cobra"
)

type fixFlags struct {
	inPlace      bool
	backup       bool
	dryRun       bool
	stripPinData bool
	envFilePath  string
}

func newFixCmd() *cobra.Command {
	flags := &fixFlags{}

	cmd := &cobra.Command{
		Use:   "fix [paths...]",
		Short: "Automatically remediate hardcoded secrets and strip test data",
		Long: `Extracts hardcoded credentials from node parameters and replaces them
with n8n environment variable expressions ({{ $env.VAR_NAME }}).
Can also export extracted credentials into an .env.example template.`,
		Example: `  # Preview automatic remediation diff without modifying files
  n8nflow-guard fix --dry-run ./workflows/invoice.json

  # Fix in place and generate an .env.example template
  n8nflow-guard fix --in-place --env-file .env.example ./workflows/

  # Strip pinned test data from workflows
  n8nflow-guard fix --in-place --strip-pindata ./workflows/`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				args = []string{"."}
			}

			files, err := resolveFixFiles(args)
			if err != nil {
				return err
			}

			if len(files) == 0 {
				fmt.Fprintln(cmd.OutOrStdout(), "No workflow files found to fix.")
				return nil
			}

			totalModified := 0
			totalSecrets := 0
			totalPinData := 0
			allEnvVars := make(map[string]string)

			opts := fixer.FixOptions{
				InPlace:      flags.inPlace,
				Backup:       flags.backup,
				DryRun:       flags.dryRun,
				StripPinData: flags.stripPinData,
			}

			for _, file := range files {
				content, err := os.ReadFile(file)
				if err != nil {
					return fmt.Errorf("failed to read %s: %w", file, err)
				}

				res, err := fixer.FixWorkflowContent(content, file, opts)
				if err != nil {
					fmt.Fprintf(cmd.ErrOrStderr(), "Warning: skipping %s: %v\n", file, err)
					continue
				}

				if res.Modified {
					totalModified++
					totalSecrets += res.SecretsReplaced
					if res.PinDataStripped {
						totalPinData++
					}
					for k, v := range res.ExtractedEnvVars {
						allEnvVars[k] = v
					}

					if flags.dryRun {
						fmt.Fprintf(cmd.OutOrStdout(), "\n--- Diff for %s ---\n", file)
						diff := fixer.GenerateUnifiedDiff(res.OriginalJSON, res.FixedJSON)
						fmt.Fprint(cmd.OutOrStdout(), diff)
					} else if flags.inPlace {
						fmt.Fprintf(cmd.OutOrStdout(), "Remediated %s (%d secrets extracted)\n", file, res.SecretsReplaced)
					}
				}
			}

			// If env file was requested and we have extracted variables
			if flags.envFilePath != "" && len(allEnvVars) > 0 && !flags.dryRun {
				var sb strings.Builder
				sb.WriteString("# Generated by n8nflow-guard fix\n")
				var keys []string
				for k := range allEnvVars {
					keys = append(keys, k)
				}
				sort.Strings(keys)
				for _, k := range keys {
					sb.WriteString(fmt.Sprintf("%s=%s\n", k, allEnvVars[k]))
				}
				if err := os.WriteFile(flags.envFilePath, []byte(sb.String()), 0644); err != nil {
					return fmt.Errorf("failed to write %s: %w", flags.envFilePath, err)
				}
				fmt.Fprintf(cmd.OutOrStdout(), "Exported %d environment variables to %s\n", len(allEnvVars), flags.envFilePath)
			}

			fmt.Fprintf(cmd.OutOrStdout(), "\nSummary: %d file(s) modified, %d secret(s) sanitized, %d pinData stripped.\n",
				totalModified, totalSecrets, totalPinData)

			if !flags.inPlace && !flags.dryRun && totalModified > 0 {
				fmt.Fprintln(cmd.OutOrStdout(), "Pass --in-place to apply these changes to disk.")
			}

			return nil
		},
	}

	cmd.Flags().BoolVarP(&flags.inPlace, "in-place", "i", false, "modify workflow files in-place on disk")
	cmd.Flags().BoolVarP(&flags.backup, "backup", "b", false, "create a .bak backup before modifying files")
	cmd.Flags().BoolVar(&flags.dryRun, "dry-run", false, "preview modifications as unified diff without saving changes")
	cmd.Flags().BoolVar(&flags.stripPinData, "strip-pindata", true, "clear pinned test data payloads")
	cmd.Flags().StringVar(&flags.envFilePath, "env-file", "", "file path to export extracted environment variables (.env.example)")

	return cmd
}

func resolveFixFiles(paths []string) ([]string, error) {
	var files []string
	for _, p := range paths {
		info, err := os.Stat(p)
		if err != nil {
			return nil, err
		}

		if !info.IsDir() {
			if strings.EqualFold(filepath.Ext(p), ".json") {
				files = append(files, p)
			}
			continue
		}

		err = filepath.WalkDir(p, func(path string, d fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if d.IsDir() {
				if d.Name() == ".git" || d.Name() == "node_modules" {
					return filepath.SkipDir
				}
				return nil
			}
			if strings.EqualFold(filepath.Ext(path), ".json") {
				files = append(files, path)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return files, nil
}
